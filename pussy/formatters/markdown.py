_FENCE_LANGUAGES = {
    "Python": "python",
    "PHP": "php",
    "JavaScript": "javascript",
    "TypeScript": "typescript",
    "Java": "java",
    "Kotlin": "kotlin",
    "Go": "go",
    "Rust": "rust",
    "C": "c",
    "C++": "cpp",
    "C#": "csharp",
    "Ruby": "ruby",
    "Swift": "swift",
    "Dart": "dart",
    "HTML": "html",
    "CSS": "css",
    "SQL": "sql",
    "Shell": "bash",
    "PowerShell": "powershell",
    "JSON": "json",
    "YAML": "yaml",
    "TOML": "toml",
    "INI": "ini",
    "XML": "xml",
    "Markdown": "markdown",
    "MDX": "mdx",
    "Dockerfile": "dockerfile",
    "Makefile": "makefile",
    "Diff": "diff",
}

_CONTENT_SECTIONS: tuple[tuple[str, frozenset[FileCategory]], ...] = (
    ("Configuration Files", frozenset({FileCategory.CONFIGURATION})),
    ("Source Code", frozenset({FileCategory.SOURCE_CODE})),
    ("Documentation", frozenset({FileCategory.DOCUMENTATION})),
    ("Database", frozenset({FileCategory.DATABASE})),
    ("Tests", frozenset({FileCategory.TESTS})),
    ("Infrastructure Files", frozenset({FileCategory.INFRASTRUCTURE})),
    (
        "Other Files",
        frozenset({FileCategory.GENERATED, FileCategory.UNKNOWN}),
    ),
)

_BACKTICKS = re.compile(r"`+")


def fence(text: str, language: str | None = None) -> str:
    """Wrap text in a code fence longer than any backtick run it contains."""
    longest = max((len(match.group(0)) for match in _BACKTICKS.finditer(text)), default=0)
    marker = "`" * max(3, longest + 1)
    info = _FENCE_LANGUAGES.get(language or "", (language or "").lower())
    info = re.sub(r"[^A-Za-z0-9_+.#-]", "", info)
    body = text.rstrip("\n")
    return f"{marker}{info}\n{body}\n{marker}"


def _escape(value: object) -> str:
    return str(value).replace("|", r"\|").replace("\n", " ")


def _bullet_list(values: Iterable[str], empty: str = "Not detected.") -> list[str]:
    items = list(values)
    if not items:
        return [empty]
    return [f"- {item}" for item in items]


class MarkdownFormatter:
    """Render a :class:`ContextBundle` as a complete Markdown document."""

    def render(self, bundle: ContextBundle) -> str:
        """Return the Markdown document."""
        sections: list[tuple[str, list[str]]] = []

        if not bundle.code_only and not bundle.tree_only:
            sections.append(("Project Overview", self._overview(bundle)))
            sections.append(("Project Metadata", self._metadata(bundle)))
        if not bundle.code_only:
            sections.append(("Directory Structure", [fence(bundle.tree, "text")]))
        if not bundle.code_only and not bundle.tree_only:
            sections.append(("Dependencies", self._dependencies(bundle)))

        if not bundle.tree_only and bundle.mode != "overview":
            sections.extend(self._file_sections(bundle))

        if not bundle.code_only and not bundle.tree_only:
            sections.append(("Git Information", self._git(bundle)))

        sections.append(("File Processing Report", self._report(bundle)))
        sections.append(("Context Statistics", self._statistics(bundle)))

        lines = [
            "# Project Context",
            "",
            f"> Generated by Pussy CLI {__version__} on "
            f"{bundle.generated_at.strftime('%Y-%m-%d %H:%M:%S UTC')} "
            f"| Mode: {bundle.mode}",
            "",
        ]
        for index, (title, body) in enumerate(sections, start=1):
            lines.append(f"## {index}. {title}")
            lines.append("")
            lines.extend(body)
            if not body or body[-1] != "":
                lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    def render_to(self, bundle: ContextBundle, stream: TextIO) -> None:
        """Write the document to an open text stream."""
        stream.write(self.render(bundle))

    # ------------------------------------------------------------------
    # Section builders
    # ------------------------------------------------------------------
    def _overview(self, bundle: ContextBundle) -> list[str]:
        project = bundle.project
        languages = ", ".join(project.languages) or "Not detected"
        frameworks = ", ".join(project.frameworks) or "Not detected"
        managers = ", ".join(project.package_managers) or "Not detected"
        entry_points = ", ".join(project.entry_points) or "Not detected"
        return [
            f"- **Project Name:** {project.name}",
            f"- **Root Directory:** `{project.root}`",
            f"- **Languages:** {languages}",
            f"- **Frameworks:** {frameworks}",
            f"- **Package Managers:** {managers}",
            f"- **Entry Points:** {entry_points}",
            f"- **Total Files:** {project.total_files}",
            f"- **Total Directories:** {project.total_directories}",
            f"- **Project Size:** {human_size(project.total_size)}",
            f"- **Dependencies:** {project.dependency_count}",
        ]

    def _metadata(self, bundle: ContextBundle) -> list[str]:
        project = bundle.project
        lines = ["### Detected Technologies", ""]
        if project.technologies:
            lines.extend(["| Technology | Kind | Evidence |", "| --- | --- | --- |"])
            for technology in project.technologies:
                lines.append(
                    f"| {_escape(technology.name)} | {_escape(technology.kind)} | "
                    f"{_escape(technology.evidence)} |"
                )
        else:
            lines.append("No technologies detected.")

        lines.extend(["", "### File Categories", ""])
        if project.category_counts:
            lines.extend(["| Category | Files |", "| --- | --- |"])
            for category, count in project.category_counts.items():
                lines.append(f"| {_escape(category)} | {count} |")
        else:
            lines.append("No files discovered.")

        lines.extend(["", "### Key Configuration Files", ""])
        config_files = project.config_files
        shown = config_files[:40]
        lines.extend(f"- `{path}`" for path in shown)
        if len(config_files) > len(shown):
            lines.append(f"- ... and {len(config_files) - len(shown)} more")
        if not config_files:
            lines.append("Not detected.")
        return lines

    def _dependencies(self, bundle: ContextBundle) -> list[str]:
        report = bundle.dependencies
        lines: list[str] = []
        if report.files_analyzed:
            lines.append(
                "Manifests analyzed: " + ", ".join(f"`{path}`" for path in report.files_analyzed)
            )
            lines.append("")
        if not report.dependencies:
            lines.append("No dependencies detected.")
            return lines

        order = ("production", "development", "build")
        grouped = report.by_scope()
        scopes = [scope for scope in order if scope in grouped]
        scopes.extend(sorted(scope for scope in grouped if scope not in order))
        for scope in scopes:
            dependencies = grouped[scope]
            lines.extend([f"### {scope.capitalize()}", ""])
            lines.extend(["| Name | Version | Source |", "| --- | --- | --- |"])
            for dependency in dependencies:
                lines.append(self._dependency_row(dependency))
            lines.append("")
        return lines

    @staticmethod
    def _dependency_row(dependency: Dependency) -> str:
        version = dependency.version or "(unspecified)"
        return f"| {_escape(dependency.name)} | {_escape(version)} | {_escape(dependency.source)} |"

    def _file_sections(self, bundle: ContextBundle) -> list[tuple[str, list[str]]]:
        entries = bundle.content_entries()
        sections: list[tuple[str, list[str]]] = []
        for title, categories in _CONTENT_SECTIONS:
            matching = [entry for entry in entries if entry.category in categories]
            if bundle.code_only and not matching:
                continue
            body: list[str] = []
            if not matching:
                body.append("No files in this category.")
            for entry in matching:
                body.extend(self._render_file(entry))
            sections.append((title, body))
        return sections

    def _render_file(self, entry: FileEntry) -> list[str]:
        lines = [
            f"### {entry.relative_path}",
            "",
            f"- **Category:** {entry.category.label}",
            f"- **Language:** {entry.language or 'Unknown'}",
            f"- **Size:** {human_size(entry.size)} ({entry.size} bytes)",
            f"- **Lines:** {entry.line_count}",
            "",
        ]
        content = entry.content or ""
        if not content:
            lines.append("_(empty file)_")
        else:
            lines.append(fence(content, entry.language))
        lines.append("")
        return lines

    def _git(self, bundle: ContextBundle) -> list[str]:
        git = bundle.git
        if git is None:
            return ["Git analysis disabled."]
        if not git.is_repo:
            return [f"Not a Git repository. {_escape(git.error or '')}".strip()]
        lines = [
            f"- **Branch:** {git.branch or '(detached HEAD)'}",
            f"- **Repository Root:** `{git.repository_root or bundle.project.root}`",
            f"- **Last Commit:** {git.commit_short or 'Unknown'} — "
            f"{git.commit_subject or 'No commits'}",
            f"- **Author:** {git.commit_author or 'Unknown'}",
            f"- **Date:** {git.commit_date or 'Unknown'}",
            f"- **Working Tree:** {'dirty' if git.is_dirty else 'clean'}",
        ]
        if git.changes:
            lines.extend(["", "### Working Tree Changes", ""])
            lines.extend(["| Status | Path |", "| --- | --- |"])
            for change in sorted(git.changes, key=lambda item: item.path.casefold()):
                lines.append(f"| {change.status} | {_escape(change.path)} |")
        if git.diff:
            lines.extend(["", "### Diff", "", fence(git.diff, "diff")])
        return lines

    def _report(self, bundle: ContextBundle) -> list[str]:
        stats = bundle.stats
        excluded = sorted(
            (entry for entry in bundle.entries if not entry.included),
            key=lambda entry: entry.relative_path.casefold(),
        )
        lines = [
            f"- **Included files:** {stats.files_included}",
            f"- **Excluded files:** {stats.files_excluded}",
            f"- **Skipped directories:** {len(bundle.project.skipped_directories)}",
            "",
        ]
        if excluded:
            lines.extend(
                ["### Excluded Files", "", "| Path | Category | Reason |", "| --- | --- | --- |"]
            )
            for entry in excluded:
                reason = entry.exclusion_reason or entry.error or "excluded"
                lines.append(
                    f"| {_escape(entry.relative_path)} | {_escape(entry.category.label)} | "
                    f"{_escape(reason)} |"
                )
            lines.append("")
        else:
            lines.extend(["No files were excluded.", ""])

        if bundle.project.skipped_directories:
            lines.extend(["### Skipped Directories", ""])
            lines.extend(f"- `{path}/`" for path in bundle.project.skipped_directories)
            lines.append("")

        if bundle.warnings:
            lines.extend(["### Warnings", ""])
            lines.extend(f"- {_escape(warning)}" for warning in bundle.warnings)
            lines.append("")
        return lines

    def _statistics(self, bundle: ContextBundle) -> list[str]:
        stats = bundle.stats
        return [
            "| Metric | Value |",
            "| --- | --- |",
            f"| Files included | {stats.files_included} |",
            f"| Files excluded | {stats.files_excluded} |",
            f"| Total files discovered | {stats.total_files} |",
            f"| Characters | {stats.characters} |",
            f"| Words | {stats.words} |",
            f"| Lines | {stats.lines} |",
            f"| Bytes | {stats.bytes} |",
            f"| Estimated tokens | {stats.estimated_tokens} |",
            f"| Tokenizer | {_escape(stats.tokenizer)} |",
            f"| Estimation method | {_escape(stats.estimation_method)} |",
            f"| Approximate | {'yes' if stats.approximate else 'no'} |",
        ]
